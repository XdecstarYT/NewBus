// Bundle the SQL migrations into a TS module so the Netlify Function can apply them on cold start.
import fs from 'node:fs';
import path from 'node:path';

const root = path.resolve(import.meta.dirname, '..');
const files = [
  ...fs.readdirSync(path.join(root, 'drizzle')).filter((f) => f.endsWith('.sql')).map((f) => path.join('drizzle', f)),
  ...fs.readdirSync(path.join(root, 'sql')).filter((f) => f.endsWith('.sql')).map((f) => path.join('sql', f)),
].sort((a, b) => path.basename(a).localeCompare(path.basename(b)));
const list = files.map((f) => ({ name: path.basename(f, '.sql'), sql: fs.readFileSync(path.join(root, f), 'utf8') }));
fs.writeFileSync(path.join(root, 'src/db/migrations.gen.ts'), `// Generated by scripts/gen-migrations.ts - do not edit.\nexport const MIGRATIONS: Array<{ name: string; sql: string }> = ${JSON.stringify(list, null, 2)};\n`);
console.log(`bundled ${list.length} migrations`);
